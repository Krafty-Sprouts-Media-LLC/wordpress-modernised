<?php

declare(strict_types=1);

namespace App\Core\Database;

use PDO;
use stdClass;

/**
 * The few places where $wpdb's own SQL depends on the database: quoting,
 * escaping, the ID after an insert, and how results are shaped. MySQL and
 * MariaDB keep WordPress's behaviour exactly; PostgreSQL gets its equivalents.
 * Plugins' own SQL is never rewritten (AGENTS.md rule 3).
 */
interface Dialect
{
    /**
     * Quotes a table or column name.
     */
    public function quoteIdentifier(string $name): string;

    /**
     * Escapes text for use inside single quotes in SQL.
     */
    public function escape(PDO $pdo, string $text): string;

    /**
     * Whether $wpdb's queries may use emulated prepares (the text protocol).
     * PostgreSQL's emulated mode would allow several statements in one query.
     */
    public function allowsEmulatedPrepares(): bool;

    /**
     * Whether PDO should turn values into text itself. PostgreSQL's driver
     * turns floats into PHP numbers first, so its text would lose digits;
     * there the connection formats floats with full precision instead.
     */
    public function stringifiesFetches(): bool;

    /**
     * The ID generated by the last insert into $table (0 if none).
     */
    public function lastInsertId(PDO $pdo, ?string $table): int;

    /**
     * Shapes a result row the way WordPress's mysqli rows look.
     *
     * @param  list<stdClass>  $columns  Column details, in mysqli_fetch_field()'s shape.
     */
    public function mapRow(stdClass $row, array $columns): stdClass;

    /**
     * Shapes column details (from mysqli_fetch_field()'s shape) the way
     * WordPress's mysqli columns look, after the rows have been mapped.
     *
     * @param  list<stdClass>  $columns
     * @return list<stdClass>
     */
    public function mapColumns(array $columns): array;

    /**
     * Turns a database error into WordPress's error number and message.
     *
     * @param  array<int, mixed>  $errorInfo  PDO's errorInfo.
     * @return array{0: int, 1: string}
     */
    public function error(array $errorInfo, string $fallbackMessage): array;
}
